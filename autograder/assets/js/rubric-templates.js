  /* 顺序讲究：越靠前越"专指"，match 打分并列时会按此顺序取先命中者。
   * 通用编程实验放在算法之前，是因为它的别名更泛（「算法」两字单独出现时
   * 不该直接判成数据结构实验）；而 ds-algo 有「红黑树」「并查集」这类
   * 高特异词兜底，真正属于它的报告不会被 T_CS 抢走。 */
  const TEMPLATES = [T_CS, T_ALGO, T_OS, T_NET, T_DB, T_SE, T_ML, T_DIGITAL, T_GENERAL];

  /**
   * 编译：模板 → 可直接被引擎消费的量表
   * 1. 字符串正则转成 RegExp（非法正则降级为永假式，不中断评分）
   * 2. 分值归一化到 100 —— 手工写的模板权重难免算错，这里统一兜底校正
   */
  function compile(tpl) {
    const conv = (arr) => (arr || []).map((s) => {
      let re;
      try { re = new RegExp(s.pattern, 'g'); } catch (e) { re = /(?!)/g; }
      return { label: s.label, w: Number(s.w) || 1, re };
    });
    const dims = (tpl.dims || []).map((d) => ({
      id: d.id,
      name: d.name,
      max: Number(d.max) || 0,
      desc: d.desc || '',
      advice: d.advice || '',
      keys: (d.keys || []).slice(),
      enabled: true,
      signals: conv(d.signals),
      penalties: conv(d.penalties),
    }));
    return normalizeScores(dims, 100);
  }

  /**
   * 分值归一化：按比例取整（下限 2 分），再把取整误差摊到最大/最小的维度上，
   * 保证合计精确等于 total，且尽量不改变原始权重排序。
   */
  function normalizeScores(dims, total) {
    total = total || 100;
    if (!dims.length) return dims;
    const sum = dims.reduce((s, d) => s + (Number(d.max) || 0), 0);
    if (!sum) {
      dims.forEach((d) => { d.max = Math.floor(total / dims.length); });
    } else {
      dims.forEach((d) => { d.max = Math.max(2, Math.round((d.max / sum) * total)); });
    }
    let cur = dims.reduce((s, d) => s + d.max, 0);
    let guard = 0;
    while (cur !== total && guard++ < 500) {
      const over = cur > total;
      // 超了就从当前最大的维度上扣，不够就补给当前最小的；min 保底 2 分不走负
      const idx = dims.reduce((bi, d, i) => (over ? (dims[bi].max < d.max ? i : bi) : (dims[bi].max > d.max ? i : bi)), 0);
      if (!over && dims[idx].max >= 40) break;      // 防止单一维度膨胀到失控
      dims[idx].max += over ? -1 : 1;
      cur = dims.reduce((s, d) => s + d.max, 0);
    }
    return dims;
  }

  function get(id) {
    return TEMPLATES.find((t) => t.id === id) || null;
  }

  function meta() {
    return TEMPLATES.map((t) => ({
      id: t.id, name: t.name, brief: t.brief,
      dimCount: t.dims.length,
      signalCount: t.dims.reduce((s, d) => s + (d.signals || []).length, 0),
    }));
  }

