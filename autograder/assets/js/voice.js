  /* ---------- 辅助：生成强项 / 弱项短语 ---------- */
  function strongPart(dims) {
    const byRatio = dims.slice().sort((a, b) => b.ratio - a.ratio);
    const top = byRatio[0], top2 = byRatio[1];
    if (!top) return '各维度均存在明显欠缺';
    if (top.ratio >= 0.85) {
      const list = [top.name].concat(top2 && top2.ratio >= 0.85 ? [top2.name] : []);
      return `${list.join('、')}完成度高`;
    }
    if (top.ratio >= 0.70) {
      const list = [top.name].concat(top2 && top2.ratio >= 0.70 ? [top2.name] : []);
      return `${list.join('、')}基本达标`;
    }
    return `相对而言 ${top.name} 写得较为完整，但各项均未达理想水平`;
  }
  function weakPart(dims) {
    return dims.slice().sort((a, b) => a.ratio - b.ratio).slice(0, 2)
      .map((d) => `${d.name}（${d.score}/${d.max}）`).join('、');
  }

  /* ---------- 维度评语 ---------- */
  function dimComment(d, tone, idx) {
    tone = tone || get();
    const lib = LIB[tone] || LIB.strict;
    const r = d.ratio;
    const band = r >= 0.85 ? 'A' : r >= 0.70 ? 'B' : r >= 0.50 ? 'C' : 'D';
    const seed = `${d.id}|${d.name}|${d.score}|${(d.evidence || []).length}|${(d.missing || []).length}`;

    const ev = (d.evidence || []).slice(0, 2).map((e) => e.label).join('、') || '关键要素';
    const miss = d.missing || [];
    // 缺失项为空时，不能输出「关键要素」这种占位词——读起来像模板没填。
    // 这种情况通常是「写了但深度不够」，改用维度名构成通顺的指代。
    const fallback = d.name + '的实质内容';
    const m0 = (miss[0] || {}).label || fallback;
    const m = miss.length
      ? miss.slice(0, 3).map((x) => '「' + x.label + '」').join('、')
      : '「' + fallback + '」';
    const a = d.advice || '';

    return pickSeq(lib[band], seed, idx)
      .replace(/\{name\}/g, d.name)
      .replace(/\{ev\}/g, ev)
      .replace(/\{m0\}/g, m0)
      .replace(/\{m\}/g, m)
      .replace(/\{a\}/g, a)
      .replace(/\s{2,}/g, ' ')
      .trim();
  }

  /* ---------- 总评 ---------- */
  function overall(total, dims, grade, tone) {
    tone = tone || get();
    const lib = OVERALL[tone] || OVERALL.strict;
    const band = total >= 85 ? 'A' : total >= 75 ? 'B' : total >= 60 ? 'C' : 'D';
    const seed = `${total}|${dims.map((d) => d.id + d.score).join(',')}`;

    return pick(lib[band], seed)
      .replace(/\{t\}/g, total)
      .replace(/\{g\}/g, (grade && grade.grade) || '')
      .replace(/\{l\}/g, (grade && grade.label) || '')
      .replace(/\{s\}/g, strongPart(dims))
      .replace(/\{w\}/g, weakPart(dims))
      .replace(/\s{2,}/g, ' ')
      .trim();
  }

