  function pickSeq(arr, seed, idx) {
    if (!arr || !arr.length) return '';
    const n = arr.length;
    const start = hash(String(seed)) % n;
    const step = (typeof idx === 'number' && idx > 0) ? idx : 0;
    return arr[(start + step) % n];
  }

